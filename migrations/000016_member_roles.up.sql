-- 000016_member_roles: роли специалистов выдаются участнику проекта
-- (решение 0030).
--
-- До сих пор «какие роли этот агент может забирать» жило только в токене
-- (agent_tokens.role_keys), а токен участник выдаёт себе сам — то есть
-- ограничение ставил тот, кого ограничивают. Теперь его ставит администратор
-- проекта на участии, а токен может только сузить дальше: действующий набор —
-- пересечение того, что разрешено участнику, и того, что разрешено токену.
--
-- NULL — любые роли проекта; пустой массив — ни одной. Та же договорённость,
-- что у токена: пусто значит «не ограничено», а не «запрещено всё».
ALTER TABLE project_members ADD COLUMN role_keys text[];

-- Команда получает те же рамки: её участники приходят в проект с уровнем
-- команды и с её набором ролей.
ALTER TABLE project_teams ADD COLUMN role_keys text[];
