-- 000034_optional_stages: необязательный этап в версии цикла (CLAB-314,
-- решение 0066, п. 1).
--
-- Отметка — данные версии цикла, как is_initial и is_terminal: правится у
-- черновика, у активной версии неизменна (решение 0016). Выбор этапов на
-- задаче — отдельная миграция части 3 (CLAB-315).
--
-- enabled_by_default — что получает новая задача, если её автор этап не
-- назвал. У обязательного статуса умолчания «выключен» не бывает: ограничение
-- держит это в базе, а 400 с понятным текстом отдаёт слой сервиса раньше.
--
-- Начальный и терминальный необязательными быть не могут, но держит это
-- валидатор, а не CHECK: черновик собирают по шагам, и промежуточное
-- состояние (статус сначала отметили, потом сделали начальным) не должно
-- отбиваться базой.
--
-- Только ADD COLUMN с постоянным умолчанием: строки не переписываются, все
-- статусы существующих версий после миграции обязательны, апгрейд базы с
-- данными идёт без ручных шагов.

ALTER TABLE workflow_statuses
    ADD COLUMN is_optional        boolean NOT NULL DEFAULT false,
    ADD COLUMN enabled_by_default boolean NOT NULL DEFAULT true;

ALTER TABLE workflow_statuses
    ADD CONSTRAINT workflow_statuses_default_needs_optional
        CHECK (is_optional OR enabled_by_default);
