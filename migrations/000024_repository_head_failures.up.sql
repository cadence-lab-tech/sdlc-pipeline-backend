-- 000024_repository_head_failures: след проваленного чтения головы ветки
-- (CLAB-79).
--
-- Плановый обход воркера читает голову каждой отслеживаемой ветки и ставит
-- прогон, если коммит новый. Когда голова не читается — приложение не
-- принято провайдером, протух секрет, ветку удалили, — прогон не заводится
-- вовсе, и до этой таблицы провал жил только в логе воркера: состояние
-- индекса показывало последний удачный прогон, как будто всё в порядке.
-- Восемнадцать дней молчавшей индексации выглядели именно так.
--
-- Отдельная таблица, а не колонки repositories: провал — свойство ветки, а
-- не репозитория (одна ветка читается, другая удалена), и строка
-- репозитория не переписывается на каждом проходе воркера.
CREATE TABLE repository_head_failures (
    repository_id   uuid NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    branch          text NOT NULL,
    -- Начало серии: «не читается с». Повторный провал его не двигает —
    -- иначе вечно сломанный репозиторий выглядел бы сломавшимся только что.
    first_failed_at timestamptz NOT NULL DEFAULT now(),
    last_failed_at  timestamptz NOT NULL DEFAULT now(),
    -- Проходов подряд. Один провал — ещё не сигнал: сеть моргнула, у
    -- провайдера лимит. Показывается серия от двух.
    failures        integer NOT NULL DEFAULT 1 CHECK (failures >= 1),
    -- Текст последней причины целиком. Класс ошибки не хранится и по тексту
    -- не узнаётся: человеку показывают сам текст.
    error           text NOT NULL,
    PRIMARY KEY (repository_id, branch)
);
