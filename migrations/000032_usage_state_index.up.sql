-- 000032_usage_state_index: поиск «прогон забирали» по индексу (CLAB-219).
--
-- Состояние учёта прогона (reported, missing, not_applicable) и долг
-- принципала по политике учёта проекта опираются на событие stage.claimed:
-- release и протухание аренды обнуляют stage_runs.claimed_by, и другого следа
-- захвата нет. У task_events был только индекс (task_id, created_at), а
-- лента — самая быстрорастущая таблица (lease.extended раз в пять минут на
-- каждую аренду): проверка долга на каждом захвате агентом, метрики проекта
-- и карточка шли бы её проходом.
--
-- Индекс частичный: stage.claimed — малая доля ленты, остальные события в
-- него не попадают и записи ленты почти не дорожают. actor_id вторым полем —
-- долг ищется по прогону и принципалу одним поиском.
--
-- Мигратор идёт транзакцией, поэтому CONCURRENTLY нельзя: на время
-- постройки запись в task_events ждёт. На наборе в 440 тысяч событий
-- индекс строится за доли секунды (оценка — в разборе изменений CLAB-219).

CREATE INDEX task_events_stage_claimed ON task_events (stage_run_id, actor_id)
    WHERE type = 'stage.claimed';
