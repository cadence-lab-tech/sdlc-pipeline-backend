-- 000036_task_events_cursor: лента проекта после курсора по индексу (CLAB-323).
--
-- Долгий опрос событий (GET /v1/projects/:key/events, GET /v1/tasks/:key/events,
-- решение 0067 п. 4) читает «события после (created_at, id)» по возрастанию, а
-- общий будильник ожидающих в каждой реплике API раз в секунду смотрит
-- события последних секунд по всей ленте. У task_events был индекс только
-- (task_id, created_at): лента задачи по нему читается, а лента проекта и
-- будильник шли бы проходом по самой быстрорастущей таблице (lease.extended
-- раз в пять минут на каждую аренду). project_id в ленте нет: выборка
-- проекта — диапазон по времени с соединением на tasks.
--
-- id вторым полем — тот же порядок, что у курсора: события одной метки
-- clock_timestamp() различаются по id, и страница не теряет хвост.
--
-- Мигратор идёт транзакцией, поэтому CONCURRENTLY нельзя: на время
-- постройки запись в task_events ждёт. На наборе в 440 тысяч событий индекс
-- строится за доли секунды (оценка — в разборе изменений CLAB-323).

CREATE INDEX task_events_cursor ON task_events (created_at, id);
