-- 000033_attachments: вложения к задаче и метаданные файла на артефакте
-- (CLAB-296, решение 0064).
--
-- Вложение — тот же артефакт, но отмеченный колонкой, а не строкой kind:
-- kind — данные контракта роли, роль вправе объявить любой, и гейт или
-- автозамена по kind засчитали бы вложение. Отметка отделяет вложения от
-- результатов этапа во всех выборках движка.
--
-- Имя и тип файла — на артефакте, а не на блобе: блобы дедуплицируются по
-- sha256, и две загрузки одних байтов под разными именами и типами
-- различались бы только здесь. У артефактов этапов, сданных строкой, оба
-- поля пусты: отдача берёт тип блоба.
--
-- indexed_at — когда индексатор прошёл артефакт, с кусками или без. Без
-- отметки артефакт, который не режется на куски (текст из одних пробелов)
-- или не пишется в базу (NUL, невалидный UTF-8), выбирался бы на каждом
-- проходе вечно. Артефакты до миграции отметки не имеют: проиндексированные
-- отсеивает наличие кусков, остальные индексатор пройдёт один раз.
--
-- Только ADD COLUMN с постоянным умолчанием или NULL: строки таблицы не
-- переписываются, апгрейд базы с данными идёт без ручных шагов.

ALTER TABLE artifacts
    ADD COLUMN is_attachment boolean NOT NULL DEFAULT false,
    ADD COLUMN file_name     text,
    ADD COLUMN media_type    text,
    ADD COLUMN indexed_at    timestamptz;

-- Вложение не принадлежит прогону и всегда несёт имя и тип: его сдают вне
-- контракта роли, и гейты по прогону его не видят. Имя — до 255 байт, как
-- в заголовке Content-Disposition у большинства клиентов.
ALTER TABLE artifacts
    ADD CONSTRAINT artifacts_attachment_shape CHECK (
        NOT is_attachment
        OR (stage_run_id IS NULL AND file_name IS NOT NULL AND media_type IS NOT NULL)),
    ADD CONSTRAINT artifacts_file_name_len CHECK (
        file_name IS NULL OR octet_length(file_name) BETWEEN 1 AND 255);

-- Список вложений задачи (карточка, захват этапа) — малая доля артефактов;
-- остальные строки в индекс не попадают.
CREATE INDEX artifacts_attachments ON artifacts (task_id, created_at) WHERE is_attachment;
