-- 000025_repo_ref_sync_failed_at: неудачная попытка синхронизации PR
-- (CLAB-84).
--
-- Воркер берёт PR в порядке synced_at NULLS FIRST с лимитом на проход.
-- Ссылка, которую не удалось прочитать (PR удалён, учётные данные
-- репозитория отказали), отметку не двигала и стояла первой вечно: стоило
-- таким набраться на лимит, остальные PR не обновлялись совсем, и гейт
-- external_check по ним ждал впустую.
--
-- Неудача пишется отдельной отметкой, а не в synced_at: гейт по synced_at
-- отличает «снимок есть» от «данных ещё нет», и непрочитанный PR не должен
-- выглядеть прочитанным. Очередь идёт по последней попытке — удачной или
-- нет; удачная отметку неудачи снимает. Вебхук по-прежнему сбрасывает
-- synced_at, и ссылка без неудачи встаёт в начало очереди.
ALTER TABLE task_repo_refs ADD COLUMN sync_failed_at timestamptz;
