-- 000030_usage_billing: признак оплаты строки учёта — деньги по ключу API или
-- условная стоимость на подписке (CLAB-216, решение 0062).
--
-- Claude Code на подписке печатает total_cost_usd по тарифу API, хотя сверх
-- подписки за прогон денег не уходит. Признак — свойство строки, а не прогона:
-- в одном прогоне могут лежать строки разных типов.
--
-- NULL — «не указано» и считается деньгами, как до миграции: бюджет —
-- защита от трат, и обойти его простым неуказанием нельзя. Строки, записанные
-- до апгрейда, получают NULL и остаются в бюджете команды.
--
-- Миграция только добавляет: ADD COLUMN без значения по умолчанию таблицу не
-- переписывает, апгрейд инстанса с данными идёт без ручных шагов. Индекс не
-- нужен: признак фильтрует те же выборки по окну и проекту.

ALTER TABLE stage_run_usage ADD COLUMN billing text
    CONSTRAINT stage_run_usage_billing_check
    CHECK (billing IN ('api', 'subscription'));
