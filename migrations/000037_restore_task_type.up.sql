-- 000037_restore_task_type: вернуть тип задачам, которым замена свойств
-- стёрла ключ `type` (CLAB-353).
--
-- PATCH /v1/tasks/:key/scope заменял properties целиком, а карточка задачи
-- шлёт по одному свойству: переключение multi_repo оставляло задаче
-- {"multi_repo": true} без `type`. Такая задача выпадала из фильтров по типу
-- (coalesce(properties->>'type', 'task') в доске, иерархии и метриках), а её
-- тип читался как `task`, хотя шла по циклу эпика или выпуска. С этой версии
-- ручка сливает свойства; миграция чинит уже случившееся на любой установке.
--
-- Тип восстанавливается по циклу задачи: tasks.workflow_id указывает на
-- конкретную версию цикла, задачи доходят по той версии, на которой начаты, а
-- у версии есть task_types — типы, для которых она заведена. Если в версии
-- ровно один тип, он однозначен: цикл эпика ведёт только эпики, цикл выпуска
-- только выпуски. Если типов несколько, настоящий тип угадать нельзя, и
-- задача не меняется: Task.Type() и фильтры и так читают её как `task`,
-- починить её можно вручную.
--
-- Правится только ключ `type`; остальные свойства, статус, область и
-- updated_at не трогаются. Миграция идемпотентна: после неё у задач с
-- однотипным циклом ключ есть, и повторный запуск ничего не находит. Пустая
-- строка в `type` считается утерянным типом так же, как отсутствующий ключ
-- (JSON null в нём запрещён ограничением tasks_type_string).
UPDATE tasks t
SET properties = t.properties || jsonb_build_object('type', w.task_types[1])
FROM workflows w
WHERE w.id = t.workflow_id
  AND cardinality(w.task_types) = 1
  AND coalesce(nullif(t.properties->>'type', ''), '') = '';
