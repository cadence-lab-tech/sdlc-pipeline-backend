-- 000043_code_files_symbols_version: каким извлечением символов получены
-- символы и куски файла индекса (CLAB-369).
--
-- Неизменённый файл прогон копирует из родителя вместе с code_symbols и
-- кусками. Без отметки новое извлечение (объявления внутри многострочных
-- литералов и заголовки в блоках кода markdown — не символы) досталось бы
-- только изменённым файлам, а ложные символы прежнего жили бы в индексе
-- ветки вечно. С отметкой прогон видит файл прежней версии и пересчитывает
-- его символы и куски из содержимого в blobs, без сети и без записи в
-- code_file_changes; копия несёт версию дальше, и следующий прогон снова
-- копирует файл (indexer.SymbolsVersion).
--
-- 0 — извлечение до CLAB-369: им построены все строки на момент миграции.
-- ADD COLUMN с постоянным DEFAULT в Postgres 11+ — правка каталога без
-- перезаписи таблицы: на большом индексе миграция мгновенна.
ALTER TABLE code_files ADD COLUMN symbols_version smallint NOT NULL DEFAULT 0;
