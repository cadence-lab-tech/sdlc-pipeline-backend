-- 000039_status_role_documents: отбор документов роли на статусе цикла
-- (CLAB-348, решение 0068, п. 3).
--
-- Роль стоит на нескольких статусах, а правила нужны ей не на всех: отбор
-- говорит «на этом статусе этап получает только эти документы версии
-- роли». Живёт на привязке роли к статусу, а не на роли: роль про статусы не
-- знает, а status_roles правится только у черновика и иммутабелен вместе с
-- активной версией цикла — набор документов прогона воспроизводится по
-- stage_runs.role_version_id и этой строке без отдельного снимка (п. 3.7).
--
-- NULL — отбора нет, этап получает все документы. Пустой список запрещён:
-- «ни одного документа» — не осмысленный выбор, а «все» уже выражает NULL,
-- и два способа сказать одно разошлись бы в связке и сравнении циклов.
-- Ссылка — по имени, а не внешним ключом на role_version_documents: версия
-- роли меняется независимо от цикла, и имя, которого в новой версии нет, —
-- предупреждение проверки, а не нарушение схемы (п. 3.6).
ALTER TABLE status_roles ADD COLUMN document_names text[]
    CONSTRAINT status_roles_document_names_not_empty
    CHECK (document_names IS NULL OR cardinality(document_names) > 0);
