-- 000035_task_optional_stages: выбор необязательных этапов на задаче
-- (CLAB-315, решение 0066, п. 7).
--
-- Объект «ключ необязательного статуса версии цикла задачи → true | false»
-- хранится полным набором: умолчания цикла разрешаются при заведении и
-- пишутся явно, поэтому правка умолчания в следующей версии цикла путь уже
-- заведённых задач молча не меняет. Ключи сверяет движок по версии цикла
-- задачи — схема их не знает, как и у stage_settings.
--
-- Отдельное поле, а не часть stage_settings: другие ключи (статусы и без
-- роли), другие права (токен задачи свою задачу не правит) и другая
-- семантика (полный набор, а не разреженное слияние).
--
-- Только ADD COLUMN с постоянным умолчанием: строки не переписываются, у
-- всех задач после миграции '{}' — выбора нет, движок проходит все статусы,
-- как до неё. Апгрейд базы с данными идёт без ручных шагов.
ALTER TABLE tasks ADD COLUMN optional_stages jsonb NOT NULL DEFAULT '{}'
    CONSTRAINT tasks_optional_stages_object
    CHECK (jsonb_typeof(optional_stages) = 'object');
