-- 000023_embedding_cache_eviction: отметка использования кэша эмбеддингов и
-- индекс под вытеснение (CLAB-12).
--
-- embedding_cache растёт монотонно: ключ у него по содержимому, владельца нет
-- намеренно (docs/SAAS.md §8), и ни удаление проекта, ни отвязка репозитория
-- его не уменьшают. Строка — это vector(1024), то есть около четырёх
-- килобайт: миллион строк даёт несколько гигабайт на общем диске инстанса.
-- Вытеснять нужно те, которыми давно не пользовались, а для этого нужно
-- знать, когда ими пользовались.

-- Колонка заводится в три шага, а не одним ADD COLUMN NOT NULL DEFAULT now():
-- при умолчании все старые строки получили бы время выкладки, и кэш, которому
-- год, притворился бы свежим на весь TTL — первое вытеснение не удалило бы
-- ничего, а оператор решил бы, что проход сломан. Когда строку использовали
-- в последний раз, неизвестно; когда её завели — известно, и врать в более
-- свежую сторону нельзя.
ALTER TABLE embedding_cache ADD COLUMN last_used_at timestamptz;
UPDATE embedding_cache SET last_used_at = created_at WHERE last_used_at IS NULL;
ALTER TABLE embedding_cache
    ALTER COLUMN last_used_at SET DEFAULT now(),
    ALTER COLUMN last_used_at SET NOT NULL;

-- По этому индексу идут оба запроса прохода вытеснения: выборка просроченных
-- и «самые давние сверху» при переполнении границы. Без него каждый проход —
-- последовательное чтение таблицы, ради которой всё и затевалось.
CREATE INDEX embedding_cache_last_used_at_idx ON embedding_cache (last_used_at);
