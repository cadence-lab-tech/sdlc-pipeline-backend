-- 000042_gate_decided_index: подсчёт апрувов по индексу (CLAB-371).
--
-- Гейт human_approval считает апрувы запросом CountApprovals по ленте
-- task_events: stage_run_id = $1 AND type = 'gate.decided' AND ... Он нужен
-- признаку awaiting_approval в списке задач, очереди апрувов (/approvals),
-- clab gates, карточке задачи и каждой попытке перехода, а у ленты были
-- только индексы (task_id, created_at), (created_at, id) и частичный
-- task_events_stage_claimed: подсчёт шёл проходом по всей ленте, самой
-- быстрорастущей таблице (lease.extended раз в пять минут на каждую аренду).
--
-- Индекс частичный: gate.decided — малая доля ленты (единицы на прогон),
-- остальные события в него не попадают и запись ленты не дорожает. Одного
-- поля stage_run_id хватает: решений на прогон единицы, граница created_at и
-- отбор по payload добираются по ним фильтром. Замер CLAB-371 на 446 тысячах
-- событий: (stage_run_id, created_at) с тем же условием даёт то же время
-- (вызов ~0,13 мс) при индексе на 40 % крупнее, а такой же индекс без
-- условия — 3,1 МБ против 56 КБ и дорожает запись каждого heartbeat'а.
--
-- Условие type = 'gate.decided' в запросе обязано быть литералом: с
-- параметром (type = $2) общий план подготовленного выражения предикат не
-- доказывает и индекс не берётся (internal/store/postgres/gates.go).
--
-- Мигратор идёт транзакцией, поэтому CONCURRENTLY нельзя: на время
-- постройки запись в task_events ждёт. На наборе в 446 тысяч событий индекс
-- строится за 25-30 мс и занимает 56 КБ (замер — в разборе изменений CLAB-371).

CREATE INDEX task_events_gate_decided ON task_events (stage_run_id)
    WHERE type = 'gate.decided';
